WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET FEEDBACK OFF
BEGIN
 EXECUTE IMMEDIATE 'CREATE TABLE DAC_CHART_BENCHMARK (SAMPLE_ID NUMBER(10) PRIMARY KEY,LOT_ID VARCHAR2(40) NOT NULL,WAFER_ID VARCHAR2(40) NOT NULL,PRODUCT VARCHAR2(40) NOT NULL,TESTED_DIES NUMBER(8) NOT NULL,GOOD_DIES NUMBER(8) NOT NULL,YIELD_PCT NUMBER(6,2) NOT NULL,INSPECTED_AT TIMESTAMP NOT NULL,DEFECT_TYPE VARCHAR2(40) NOT NULL,SEVERITY VARCHAR2(10) NOT NULL,DEFECT_COUNT NUMBER(8) NOT NULL)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/
MERGE INTO DAC_CHART_BENCHMARK t
USING (
 SELECT n,'BENCH-'||LPAD(MOD(n-1,10)+1,3,'0') lot,
 'W'||LPAD(n,7,'0') wafer,
 CASE MOD(TRUNC((n-1)/10),3) WHEN 0 THEN 'DRAM' WHEN 1 THEN 'NAND' ELSE 'SRAM' END product,
 1000 tested,
 LEAST(1000,ROUND(910+45*SIN(n/137)+MOD(n*7919,80))) good,
 TIMESTAMP '2026-10-01 00:00:00' + NUMTODSINTERVAL(n,'SECOND') inspected,
 CASE MOD(TRUNC((n-1)/10),3) WHEN 0 THEN 'SCRATCH' WHEN 1 THEN 'PARTICLE' ELSE 'BRIDGE' END defect,
 CASE MOD(TRUNC((n-1)/30),4) WHEN 0 THEN 'LOW' WHEN 1 THEN 'MEDIUM' WHEN 2 THEN 'HIGH' ELSE 'CRITICAL' END severity
 FROM (SELECT LEVEL n FROM dual CONNECT BY LEVEL<=1000000)
) s ON(t.SAMPLE_ID=s.n)
WHEN NOT MATCHED THEN INSERT VALUES(s.n,s.lot,s.wafer,s.product,s.tested,s.good,s.good/10,s.inspected,s.defect,s.severity,GREATEST(1,1000-s.good));
UPDATE DAC_CHART_BENCHMARK SET GOOD_DIES=TESTED_DIES,YIELD_PCT=100 WHERE GOOD_DIES>TESTED_DIES;
COMMIT;
SELECT COUNT(*) BENCHMARK_ROWS FROM DAC_CHART_BENCHMARK;
EXIT;
